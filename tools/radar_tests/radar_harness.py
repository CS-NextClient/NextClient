#!/usr/bin/env python3
"""Unattended advanced-radar regression run.

Drives a deterministic demo through the game and collects the captures the in-client
scheduler produces, then diffs them against committed goldens. No manual console input:
the harness drops a plan file the client auto-loads (RadarTestPlan), launches the demo,
waits for the client's done-marker, and terminates the game.

    python radar_harness.py CONFIG.json [--update] [--keep]

    --update  copy the produced captures over the goldens instead of diffing (use once
              to (re)establish goldens on this machine/resolution).
    --keep    do not delete the produced captures from the game dir after the run.

Config (JSON):
    {
      "exe": "D:/Counter Strike 1.6 steam next client/cstrike.exe",
      "gamedir": "D:/Counter Strike 1.6 steam next client/cstrike",
      "launch_args": ["-game", "cstrike", "-windowed",
                      "-width", "{width}", "-height", "{height}",
                      "+host_framerate", "0.013333", "+playdemo", "{demo}"],
      "demo": "radar_test",
      "resolution": "1280x1024",
      "golden_dir": "goldens",
      "timeout": 180,
      "tol": 12,
      "fail_frac": 0.002,
      "steps": [
        {"time": 3.0, "name": "pistol", "dump": true, "shot": true},
        {"time": 8.5, "name": "smoke",  "shot": true, "region": [0, 0, 320, 320]}
      ]
    }

Exit code 0 = every step within tolerance, 1 = a difference/missing capture, 2 = setup
error. Goldens are machine- and resolution-bound; see README.md.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

try:
    from imgdiff import compare_images
except ImportError as e:
    sys.stderr.write(f"radar_harness: cannot import imgdiff ({e})\n")
    sys.exit(2)

PLAN_NAME = "radar_testplan.txt"
DONE_NAME = "radar_testplan.done"


def fail(msg):
    sys.stderr.write(f"radar_harness: {msg}\n")
    sys.exit(2)


def step_action(step):
    if step.get("dump") and step.get("shot"):
        return "both"
    return "dump" if step.get("dump") else "shot"


def plan_line(step, resolution):
    """The radar_testplan line a step generates (the client appends _<i> for 'every')."""
    base = f"{step['name']}_{resolution}"
    action = step_action(step)
    trig = step.get("trigger", "at")
    if trig == "every":
        return f"every {float(step['interval'])} {int(step.get('count', 1))} {action} {base}"
    if trig == "on":
        ev = step["event"]
        if "delay" in step:
            return f"on {ev} {float(step['delay'])} {action} {base}"
        return f"on {ev} {action} {base}"
    return f"at {float(step['time'])} {action} {base}"


def step_outputs(step, resolution):
    """Yield (base, ext, region) for every file a step produces.

    'every' produces count captures named <name>_<res>_<i>; the others one named
    <name>_<res>. region applies only to image (tga) diffs.
    """
    name = step["name"]
    region = step.get("region")
    exts = [e for e, k in (("tga", "shot"), ("json", "dump")) if step.get(k)]
    if step.get("trigger") == "every":
        bases = [f"{name}_{resolution}_{i}" for i in range(int(step.get("count", 1)))]
    else:
        bases = [f"{name}_{resolution}"]
    for base in bases:
        for ext in exts:
            yield base, ext, region


def write_plan(cfg, plan_path):
    lines = ["# generated by radar_harness.py - do not edit", "quit_after_last 1"]
    lines += [plan_line(st, cfg["resolution"]) for st in cfg["steps"]]
    with open(plan_path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def produced_files(cfg):
    """Map of (base, ext) -> absolute path for every capture the plan should create."""
    out = {}
    for st in cfg["steps"]:
        for base, ext, _ in step_outputs(st, cfg["resolution"]):
            out[(base, ext)] = os.path.join(cfg["gamedir"], f"{base}.{ext}")
    return out


def clean(paths):
    for p in paths:
        try:
            os.remove(p)
        except FileNotFoundError:
            pass


def launch(cfg):
    width, height = cfg["resolution"].lower().split("x")
    args = [
        a.replace("{demo}", cfg["demo"]).replace("{width}", width).replace("{height}", height)
        for a in cfg["launch_args"]
    ]
    return subprocess.Popen([cfg["exe"], *args], cwd=os.path.dirname(cfg["exe"]) or None)


def wait_for_done(done_path, proc, timeout):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if os.path.exists(done_path):
            return True
        if proc.poll() is not None:
            # The game exited; give the marker a moment in case of a flush race.
            time.sleep(0.5)
            return os.path.exists(done_path)
        time.sleep(0.5)
    return False


def stop(proc):
    if proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()


def load_dump(path):
    with open(path, encoding="ascii") as f:
        data = json.load(f)
    index = {}
    for m in data.get("markers", []):
        index[(m["kind"], m["id"])] = m
    return data, index


def compare_dumps(golden_path, check_path, pos_tol=1.5):
    g, gi = load_dump(golden_path)
    c, ci = load_dump(check_path)
    diffs = []
    for key, gm in gi.items():
        cm = ci.get(key)
        if cm is None:
            diffs.append(f"missing {key}")
            continue
        for fld in ("wx", "wy", "sx", "sy"):
            if abs(gm[fld] - cm[fld]) > pos_tol:
                diffs.append(f"{key} {fld} {gm[fld]:.1f}->{cm[fld]:.1f}")
        for fld in ("r", "g", "b", "a"):
            if gm[fld] != cm[fld]:
                diffs.append(f"{key} {fld} {gm[fld]}->{cm[fld]}")
        if gm.get("flags", "") != cm.get("flags", ""):
            diffs.append(f"{key} flags '{gm.get('flags')}'->'{cm.get('flags')}'")
    for key in ci:
        if key not in gi:
            diffs.append(f"extra {key}")
    passed = not diffs
    summary = "match" if passed else "; ".join(diffs[:8]) + (" ..." if len(diffs) > 8 else "")
    return passed, summary


def diff_all(cfg, golden_dir):
    overall = True
    for st in cfg["steps"]:
        for base, ext, region in step_outputs(st, cfg["resolution"]):
            check = os.path.join(cfg["gamedir"], f"{base}.{ext}")
            golden = os.path.join(golden_dir, f"{base}.{ext}")
            if ext == "tga":
                overall &= report(
                    base, "shot", check, golden,
                    lambda c=check, g=golden, r=region, b=base: compare_images(
                        g, c, r, cfg.get("tol", 12), cfg.get("fail_frac", 0.002),
                        os.path.join(cfg["gamedir"], b + "_diff.png"),
                    ),
                )
            else:
                overall &= report(
                    base, "dump", check, golden,
                    lambda c=check, g=golden: compare_dumps(g, c),
                )
    return overall


def report(base, kind, check, golden, comparator):
    if not os.path.exists(check):
        print(f"FAIL  {base} [{kind}]  capture not produced")
        return False
    if not os.path.exists(golden):
        print(f"FAIL  {base} [{kind}]  no golden (run with --update first)")
        return False
    try:
        passed, summary = comparator()
    except OSError as e:
        print(f"FAIL  {base} [{kind}]  {e}")
        return False
    print(f"{'PASS' if passed else 'FAIL'}  {base} [{kind}]  {summary}")
    return passed


def update_goldens(cfg, golden_dir):
    os.makedirs(golden_dir, exist_ok=True)
    n = 0
    for (base, ext), src in produced_files(cfg).items():
        if not os.path.exists(src):
            print(f"SKIP  {base}.{ext}  not produced")
            continue
        shutil.copy2(src, os.path.join(golden_dir, f"{base}.{ext}"))
        print(f"UPDATED  {base}.{ext}")
        n += 1
    print(f"updated {n} golden(s) in {golden_dir}")
    return n > 0


def main():
    ap = argparse.ArgumentParser(description="Unattended advanced-radar regression run.")
    ap.add_argument("config")
    ap.add_argument("--update", action="store_true", help="(re)capture goldens instead of diffing")
    ap.add_argument("--keep", action="store_true", help="keep produced captures in the game dir")
    args = ap.parse_args()

    try:
        with open(args.config, encoding="utf-8") as f:
            cfg = json.load(f)
    except OSError as e:
        fail(str(e))

    for req in ("exe", "gamedir", "launch_args", "demo", "resolution", "steps"):
        if req not in cfg:
            fail(f"config missing '{req}'")
    if not os.path.isfile(cfg["exe"]):
        fail(f"exe not found: {cfg['exe']}")
    if not os.path.isdir(cfg["gamedir"]):
        fail(f"gamedir not found: {cfg['gamedir']}")

    golden_dir = cfg.get("golden_dir", "goldens")
    if not os.path.isabs(golden_dir):
        golden_dir = os.path.join(os.path.dirname(os.path.abspath(args.config)), golden_dir)

    plan_path = os.path.join(cfg["gamedir"], PLAN_NAME)
    done_path = os.path.join(cfg["gamedir"], DONE_NAME)
    outputs = list(produced_files(cfg).values())

    clean([plan_path, done_path, *outputs])
    write_plan(cfg, plan_path)

    print(f"launching {os.path.basename(cfg['exe'])} demo={cfg['demo']} @ {cfg['resolution']} ...")
    proc = launch(cfg)
    try:
        ok = wait_for_done(done_path, proc, cfg.get("timeout", 180))
    finally:
        stop(proc)

    if not ok:
        sys.stderr.write(
            "radar_harness: timed out waiting for the done-marker. Check that the demo "
            "exists, plays the advanced radar, and the step times fit within it.\n"
        )

    try:
        if args.update:
            success = update_goldens(cfg, golden_dir)
        else:
            success = diff_all(cfg, golden_dir)
    finally:
        if not args.keep:
            diff_pngs = [
                os.path.join(cfg["gamedir"], base + "_diff.png")
                for s in cfg["steps"]
                for base, ext, _ in step_outputs(s, cfg["resolution"])
                if ext == "tga"
            ]
            clean([plan_path, done_path, *outputs, *diff_pngs])

    return 0 if (ok and success) else 1


if __name__ == "__main__":
    sys.exit(main())
